import { test, expect } from '@playwright/test'
import path from 'node:path'

async function openDemo(page:import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('button',{name:'体验合成演示',exact:true}).click()
  await expect(page.getByRole('button',{name:'运行分析',exact:true})).toBeEnabled()
  await expect(page.locator('.matrix-cell')).toHaveCount(21)
}
async function analyze(page:import('@playwright/test').Page) {
  await page.getByRole('button',{name:'运行分析',exact:true}).click()
  await expect(page.getByRole('button',{name:'运行分析',exact:true})).toBeEnabled()
  await expect(page.locator('.notice.stale')).toHaveCount(0)
}

test('home → demo → choose result → matrix → evidence → correction → reopen → all exports',async({page})=>{
  const browserErrors:string[]=[]
  page.on('pageerror',e=>browserErrors.push(e.message))
  const remote:string[]=[]
  await page.route('**/*',async route=>{
    const url=new URL(route.request().url())
    if(['http:','https:'].includes(url.protocol)&&url.hostname!=='127.0.0.1'){
      remote.push(url.origin);await route.abort()
    }else await route.continue()
  })
  await openDemo(page)
  const selected=page.getByLabel('论文 1 活动结果')
  const mainId=await selected.inputValue()
  await selected.selectOption({index:2})
  await expect(page.locator('.notice.stale')).toBeVisible()
  await expect(selected).toBeEnabled()
  await selected.selectOption(mainId)
  await expect(selected).toBeEnabled()
  await analyze(page)
  const split=page.getByRole('button',{name:'已报告 Evaluation split: temporal split. 合成演示 原文已定位',exact:true})
  await split.click()
  await expect(page.locator('.evidence-card blockquote')).toHaveText('Evaluation split: temporal split.')
  await page.getByText('提取页面文本 · 精确片段',{exact:true}).click()
  await expect(page.locator('.evidence-card mark')).toHaveText('Evaluation split: temporal split.')
  await page.getByRole('button',{name:'查看 PDF 第 2 页',exact:true}).click()
  await expect(page.locator('.pdf-page .muted')).toHaveCount(0,{timeout:10000})
  await expect(page.locator('.pdf-page canvas')).toBeVisible()
  await page.locator('.interpretation').getByRole('button',{name:'修订',exact:true}).click()
  await page.getByLabel('字段值 / 说明').fill('Evaluation split: temporal split.（用户复核）')
  await page.getByLabel('修订理由').fill('核对第 2 页，保留原记录并细化解释。')
  await page.getByRole('button',{name:'保存修订',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.notice.stale')).toBeVisible()
  await expect(page.locator('.inspector-history')).toContainText('核对第 2 页')
  const projectUrl=page.url()
  await page.getByRole('button',{name:'全部项目',exact:true}).click()
  await expect(page.getByRole('heading',{name:'让文献比较，有据可循。',exact:true})).toBeVisible()
  await page.goto(projectUrl)
  await expect(page.locator('.matrix-cell').filter({hasText:'用户复核'})).toHaveCount(1)
  for(const [label,extension] of [['Markdown 报告','.md'],['JSON 数据','.json'],['CSV 数据','.csv']]){
    await page.getByRole('button',{name:'导出报告',exact:true}).click()
    const downloadPromise=page.waitForEvent('download')
    await page.getByRole('button',{name:label,exact:true}).click()
    const download=await downloadPromise
    expect(download.suggestedFilename().endsWith(extension)).toBe(true)
    const fs=await import('node:fs/promises')
    const output=await fs.readFile((await download.path())!,'utf8')
    expect(output).toContain('用户复核')
    expect(output).toContain('STALE')
    expect(output).toContain('SYNTHETIC DEMO')
  }
  expect(browserErrors).toEqual([])
  expect(remote).toEqual([])
})

