test('arbitrary PDF upload path → manual result → evidence → fields → correction → save',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'新建比较项目',exact:true}).click()
  await page.getByLabel('项目名称').fill('浏览器手工工作流')
  await page.getByLabel('具体比较问题').fill('哪些论文报告了结果？')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  for(const letter of ['A','B']){
    await page.getByRole('button',{name:'添加 PDF',exact:true}).click()
    await page.getByLabel('选择 PDF').setInputFiles(path.resolve(import.meta.dirname,'../../../src/comparison_workspace/demo/fixtures/paper_'+letter+'.pdf'))
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  await expect(page.locator('.demo-strip')).toContainText('SYNTHETIC DEMO / NOT RESEARCH EVIDENCE')
  await expect(page.getByLabel('演示问题')).toHaveCount(0)
  for(let index=0;index<2;index++){
    await page.getByRole('button',{name:'手工添加',exact:true}).nth(index).click()
    await page.getByLabel('结果名称').fill('手工主实验')
    await page.getByLabel('实验 / 结果身份').fill('manual-primary-'+index)
    await page.getByRole('button',{name:'保存',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
  await page.getByLabel('阅读论文 1').click()
  await page.getByRole('button',{name:'定位证据',exact:true}).click()
  await page.getByLabel('PDF 页码').fill('2')
  await page.getByLabel('精确引文').fill('Primary experiment: Accuracy 92%.')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:'添加比较维度',exact:true}).click()
  await page.getByLabel('比较维度').fill('报告结果')
  await page.getByLabel('字段值 / 说明').fill('Accuracy 92%')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.matrix-cell')).toContainText('92%')
  await page.getByLabel('修订论文 1 目标结果').click()
  await page.getByLabel('结果名称').fill('用户复核的主实验')
  await page.getByLabel('修订理由').fill('确认目标实验，保留最初手工记录。')
  await page.getByRole('button',{name:'保存修订',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:'保存手工对照',exact:true}).click()
  await expect(page.getByRole('button',{name:'保存手工对照',exact:true})).toBeEnabled()
  await page.reload()
  await expect(page.getByLabel('论文 1 活动结果')).toContainText('用户复核的主实验')
})

test('1440×900, 1280×800 and narrow layout have no page overflow',async({page})=>{
  await openDemo(page)
  for(const size of [{width:1440,height:900},{width:1280,height:800},{width:390,height:844}]){
    await page.setViewportSize(size)
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)
    expect(overflow).toBe(false)
    await page.getByRole('button',{name:'已报告 Evaluation split: temporal split. 合成演示 原文已定位',exact:true}).click()
    await expect(page.locator('.inspector.is-open')).toBeVisible()
    await page.getByRole('button',{name:'关闭证据检查器',exact:true}).click()
  }
})

test('corrected finding survives rerun and becomes historical when the question changes',async({page})=>{
  await openDemo(page)
  await page.locator('.finding-card').filter({hasText:'三篇合成文献均定位到'}).click()
  await page.locator('.interpretation').getByRole('button',{name:'修订',exact:true}).click()
  await expect(page.getByRole('dialog').getByRole('checkbox',{name:/Aster/}).first()).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('checkbox',{name:/Birch/}).first()).toBeVisible()
  await page.getByLabel('解释与理由').fill('人工复核保留的解释')
  await page.getByLabel('修订理由').fill('核对原始提议与源页，保留来源。')
  await page.getByRole('button',{name:'保存修订',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await analyze(page)
  await expect(page.locator('.finding-list')).toContainText('人工复核保留的解释')
  await expect(page.locator('.finding-list')).toContainText('用户修订')
  await page.getByLabel('演示问题').selectOption('protocol')
  await expect(page.locator('.notice.stale')).toBeVisible()
  await page.getByRole('button',{name:'运行分析',exact:true}).click()
  await expect(page.getByRole('button',{name:'运行分析',exact:true})).toBeEnabled()
  await expect(page.locator('.finding-list')).not.toContainText('人工复核保留的解释')
  await expect(page.locator('.notice.stale')).toBeVisible()
  await page.getByText('STALE · 历史判断（1）',{exact:true}).click()
  await expect(page.locator('.stale-findings')).toContainText('人工复核保留的解释')
  await page.reload()
  await expect(page.locator('.notice.stale')).toBeVisible()
})

test('switching away from a corrected observation clears the inspector and can rerun',async({page})=>{
  await openDemo(page)
  await page.getByRole('button',{name:'已报告 Evaluation split: temporal split. 合成演示 原文已定位',exact:true}).click()
  await page.locator('.interpretation').getByRole('button',{name:'修订',exact:true}).click()
  await page.getByLabel('字段值 / 说明').fill('Evaluation split: temporal split.（复核）')
  await page.getByLabel('修订理由').fill('检查主实验划分。')
  await page.getByRole('button',{name:'保存修订',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('论文 2 活动结果').selectOption({index:2})
  await expect(page.locator('.interpretation')).toHaveCount(0)
  await analyze(page)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.matrix-cell')).toHaveCount(21)
  await page.getByRole('tab',{name:'未决 1',exact:true}).click()
  await expect(page.locator('.finding-list')).toContainText('内置演示结论不再适用')
})
